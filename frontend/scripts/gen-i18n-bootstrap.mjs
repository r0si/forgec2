#!/usr/bin/env node
// gen-i18n-bootstrap.mjs — generate src/lib/i18n/bootstrap.ts, the slice of the
// English dictionary that must exist before the async full dictionary resolves.
//
// The full `en` dictionary is ~239 kB of the first-paint path (docs/FRONTEND_PERF.md).
// Only the shell needs to be synchronous: nav, topbar, section headings, a11y
// labels, login, error text and `common.*`. Everything else is loaded with the
// route chunks and merged in.
//
// Usage:
//   node scripts/gen-i18n-bootstrap.mjs          # rewrite bootstrap.ts
//   node scripts/gen-i18n-bootstrap.mjs --check  # exit 1 if it would change
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const enPath = join(root, "src", "lib", "i18n", "en.ts");
const outPath = join(root, "src", "lib", "i18n", "bootstrap.ts");
const checkOnly = process.argv.includes("--check");

// Namespaces the shell renders before any route chunk loads.
const BOOTSTRAP_PREFIXES = [
  "nav.",
  "topbar.",
  "section.",
  "a11y.",
  "common.",
  "login.",
  "error.",
];

const src = readFileSync(enPath, "utf8");
// Entries are single-line: `"key": "value",`
const entries = [...src.matchAll(/^\s*"([^"]+)":\s*"((?:[^"\\]|\\.)*)",\s*$/gm)].map((m) => ({
  key: m[1],
  value: m[2],
}));
if (entries.length === 0) {
  console.error("gen-i18n-bootstrap: no entries parsed from en.ts");
  process.exit(1);
}

const picked = entries.filter((e) => BOOTSTRAP_PREFIXES.some((p) => e.key.startsWith(p)));
const lines = picked.map((e) => `  "${e.key}": "${e.value}",`);

const out = `// GENERATED by scripts/gen-i18n-bootstrap.mjs — do not edit by hand.
//
// The synchronous slice of the English dictionary: what the shell (sidebar,
// topbar, section headings, login, a11y labels, error text) needs before the
// full dictionary chunk arrives. Everything else lives in en.ts and is merged
// in by the provider once it loads.
//
// check:openapi-style drift is prevented by \`node scripts/gen-i18n-bootstrap.mjs --check\`
// (wired as check:i18n-bootstrap).
export const enBootstrap: Record<string, string> = {
${lines.join("\n")}
};
`;

if (checkOnly) {
  const current = (() => {
    try {
      return readFileSync(outPath, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== out) {
    console.error(
      `gen-i18n-bootstrap: bootstrap.ts is stale (${picked.length} keys expected). Run \`node scripts/gen-i18n-bootstrap.mjs\`.`,
    );
    process.exit(1);
  }
  console.log(`i18n bootstrap OK — ${picked.length} shell keys`);
  process.exit(0);
}

writeFileSync(outPath, out, "utf8");
console.log(`gen-i18n-bootstrap: wrote ${picked.length} keys to bootstrap.ts`);
