package server

import (
	"encoding/json"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/forgec2/forgec2/internal/db"
	"github.com/forgec2/forgec2/internal/plugin"
	"gopkg.in/yaml.v3"
)

// AI-authored plugins.
//
// The assistant can write a plugin package (manifest + entry) for the operator instead of only
// suggesting code to paste. Three properties make that safe to expose:
//
//   - it is ADMIN only and goes through the approval intent for every write tool, so `plugins.write`
//     and a human approval are both required before anything lands on disk;
//   - it NEVER executes the plugin. Writing, validating and registering are separate from running, and
//     running still needs `plugins.execute` through the normal page - a generated command is code, and
//     code is reviewed before it runs;
//   - it writes through the same path as a manual install: name/entry are checked for separators and
//     `..`, the manifest goes through `plugin.Manifest.Validate`, and `Register` rejects duplicates and
//     unresolvable dependencies. On any failure the directory is removed, so a rejected proposal leaves
//     no half-installed package behind.

const (
	// aiPluginCodeMaxBytes bounds the entry file the assistant may write. A plugin that needs more is
	// not something to generate in a chat turn.
	aiPluginCodeMaxBytes = 64 * 1024
	// aiPluginNamePattern keeps the name usable as a directory name on every platform.
	aiPluginNamePattern = `^[a-z0-9][a-z0-9_-]{1,63}$`
)

// aiPluginEntryByInterpreter picks the conventional file name for the interpreter, so the model only
// has to supply code.
var aiPluginEntryByInterpreter = map[string]string{
	"python":     "plugin.py",
	"python3":    "plugin.py",
	"powershell": "plugin.ps1",
	"pwsh":       "plugin.ps1",
	"bash":       "plugin.sh",
	"sh":         "plugin.sh",
	"go":         "plugin.go",
	"wasm":       "plugin.wasm",
}

var aiPluginNameRE = regexp.MustCompile(aiPluginNamePattern)

// aiCreatePluginArgs is the model-facing argument set.
type aiCreatePluginArgs struct {
	Name        string `json:"name"`
	Description string `json:"description"`
	Type        string `json:"type"`
	Interpreter string `json:"interpreter"`
	Code        string `json:"code"`
	Entry       string `json:"entry"`
	Timeout     int    `json:"timeout"`
	Category    string `json:"category"`
}

// aiCreatePluginTool writes, validates and registers a plugin package, and returns what it did.
func (s *Server) aiCreatePluginTool(reqCtx *aiReqCtx, argsJSON string) string {
	if s.pluginManager == nil {
		return `{"error":"the plugin manager is not available on this server"}`
	}
	var args aiCreatePluginArgs
	if err := json.Unmarshal([]byte(argsJSON), &args); err != nil {
		return `{"error":"invalid arguments: ` + sanitizeError(err, "plugin") + `"}`
	}

	name := strings.ToLower(strings.TrimSpace(args.Name))
	if !aiPluginNameRE.MatchString(name) {
		return `{"error":"invalid name: use 2-64 lowercase letters, digits, '-' or '_' (it becomes a directory name)"}`
	}
	if len(name) > 64 {
		return `{"error":"invalid name: too long"}`
	}
	interpreter := strings.ToLower(strings.TrimSpace(args.Interpreter))
	if _, ok := aiPluginEntryByInterpreter[interpreter]; !ok {
		keys := make([]string, 0, len(aiPluginEntryByInterpreter))
		for key := range aiPluginEntryByInterpreter {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		return `{"error":"invalid interpreter, must be one of ` + strings.Join(keys, ", ") + `"}`
	}
	code := args.Code
	if strings.TrimSpace(code) == "" {
		return `{"error":"code is required"}`
	}
	if len(code) > aiPluginCodeMaxBytes {
		return fmt.Sprintf(`{"error":"code is too large: %d bytes, limit %d"}`, len(code), aiPluginCodeMaxBytes)
	}
	entry := strings.TrimSpace(args.Entry)
	if entry == "" {
		entry = aiPluginEntryByInterpreter[interpreter]
	}
	if strings.ContainsAny(entry, `/\`) || strings.Contains(entry, "..") || filepath.IsAbs(entry) {
		return `{"error":"invalid entry: must be a plain file name inside the plugin directory"}`
	}

	pluginType := strings.ToLower(strings.TrimSpace(args.Type))
	if pluginType == "" {
		pluginType = "command"
	}
	timeout := args.Timeout
	if timeout <= 0 {
		timeout = 60
	}

	manifest := plugin.Manifest{
		Name:        name,
		Version:     "1.0.0",
		Type:        pluginType,
		Description: strings.TrimSpace(args.Description),
		Author:      "forgec2-ai",
		Category:    strings.TrimSpace(args.Category),
		Entry:       entry,
		Interpreter: interpreter,
		Timeout:     timeout,
	}
	if manifest.Description == "" {
		manifest.Description = "Generated by the ForgeC2 assistant"
	}
	// A command plugin needs at least one parameter or the console has nothing to fill in.
	if manifest.Type == "command" {
		manifest.Params = []plugin.ManifestParam{{
			Name:        "input",
			Type:        "string",
			Description: "Free-form input passed to the plugin",
			Required:    false,
		}}
	}
	// Validate before touching the disk, so a bad proposal costs nothing.
	if err := manifest.Validate(); err != nil {
		return fmt.Sprintf(`{"error":"manifest rejected: %s"}`, strings.ReplaceAll(sanitizeError(err, "plugin"), `"`, "'"))
	}

	dir := s.pluginManager.PluginDir(name)
	// Refuse to touch an existing package BEFORE creating anything: the cleanup below removes the
	// directory on failure, and for a duplicate name that directory is the plugin that already exists -
	// a rejected duplicate would otherwise delete a working plugin.
	if _, statErr := os.Stat(dir); statErr == nil {
		return `{"error":"a plugin with this name already exists; edit or delete it from the Plugins page instead"}`
	} else if !os.IsNotExist(statErr) {
		return `{"error":"failed to inspect the plugin directory"}`
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return `{"error":"failed to create the plugin directory"}`
	}
	// From here on a failure must leave nothing behind.
	committed := false
	defer func() {
		if !committed {
			if err := os.RemoveAll(dir); err != nil {
				slog.Warn("AI plugin: failed to clean up a rejected package", "plugin", name, "err", err)
			}
		}
	}()

	manifestData, err := yaml.Marshal(&manifest)
	if err != nil {
		return `{"error":"failed to render the manifest"}`
	}
	if err := os.WriteFile(filepath.Join(dir, "manifest.yaml"), manifestData, 0o600); err != nil {
		return `{"error":"failed to write the manifest"}`
	}
	if err := os.WriteFile(filepath.Join(dir, entry), []byte(code), 0o600); err != nil {
		return `{"error":"failed to write the plugin code"}`
	}
	if err := s.pluginManager.Register(&manifest); err != nil {
		return fmt.Sprintf(`{"error":"registration rejected: %s"}`, strings.ReplaceAll(sanitizeError(err, "plugin"), `"`, "'"))
	}
	committed = true

	// Mirror the manual install path: the record exists and is enabled, which is what makes the plugin
	// visible in the console. Execution stays a separate, explicit, permission-gated action.
	record := db.Plugin{Name: manifest.Name}
	if err := s.db.Where(&db.Plugin{Name: manifest.Name}).
		Assign(db.Plugin{
			Version:     manifest.Version,
			Description: manifest.Description,
			Author:      manifest.Author,
			Type:        manifest.Type,
			Category:    manifest.Category,
			Enabled:     true,
		}).FirstOrCreate(&record).Error; err != nil {
		return fmt.Sprintf(`{"error":"plugin registered on disk but the record could not be saved: %s"}`,
			strings.ReplaceAll(sanitizeError(err, "plugin"), `"`, "'"))
	}

	// Audited like a manual install; nil context is fine for the non-HTTP call path.
	user := "ai"
	if reqCtx != nil && reqCtx.Principal.Username != "" {
		user = reqCtx.Principal.Username
	}
	s.LogAuditRecord(nil, "plugin_create_ai", "plugin", manifest.Name,
		fmt.Sprintf("assistant wrote plugin %s (%s, %s) on behalf of %s", manifest.Name, manifest.Type, interpreter, user), true, nil)

	out, ok := marshalJSONSafe(map[string]interface{}{
		"created":     true,
		"name":        manifest.Name,
		"version":     manifest.Version,
		"type":        manifest.Type,
		"interpreter": interpreter,
		"entry":       entry,
		"path":        dir,
		"note":        "written and registered but NOT executed; run it from the Plugins page (plugins.execute) after reviewing the code",
	})
	if !ok {
		return `{"error":"failed to marshal the result"}`
	}
	return string(out)
}
